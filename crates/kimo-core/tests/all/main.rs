//! The integration tests of kimo-core, linked into one test binary (`all`) instead of one binary per file.
//! Each former `tests/<name>.rs` is the module `<name>`, so nextest names a test `<name>::<test>`.
//! Shared fixtures live in `common/` and are included by `#[path]` from the modules that use them.

// `subject_match` compiles src/color/subject_match.rs into this binary; that file names
// `crate::{color, effects, guard}`, which must resolve at this crate root.
#[allow(unused_imports)]
use kimo_core::{color, effects, guard};

/// Path of a test fixture in the OS temp directory (std::env::temp_dir()); a hard-coded /tmp does not exist on Windows.
pub(crate) fn tmp(name: &str) -> String { std::env::temp_dir().join(name).to_string_lossy().into_owned() }

